// instance-create
//
// Admin-only. Provisions a new WhatsApp number on the Evolution API and
// stores its DB row with encrypted per-instance token + webhook secret.
//
// Flow:
//   1. Allocate Supabase UUID `id` ahead of time so we can embed it in the
//      Evolution webhook URL.
//   2. Generate unique evolution_instance_name, per-instance token, and
//      per-instance webhook secret.
//   3. INSERT whatsapp_instances row (status=pending). Trigger auto-creates
//      number_pacing_state row.
//   4. Store encrypted token + webhook secret via DEFINER helpers.
//   5. POST /instance/create at Evolution with webhook config pointing at
//      http://wa-mancer-worker:8090/webhook/<id>.
//   6. If Evolution fails → DELETE the DB row (cleanup) and return error.
//   7. On success, return { id, display_name, evolution_instance_name }.
//
// Required env (set via `supabase secrets set`):
//   EVOLUTION_API_URL          — https://api.welcomdeal.ma
//   EVOLUTION_GLOBAL_API_KEY   — global admin key
//   WORKER_WEBHOOK_URL_BASE    — internal docker URL the worker listens on
//                                e.g. http://wa-mancer-worker:8090/webhook
//                                Note: this is from Evolution's perspective;
//                                resolves via docker internal DNS.

import 'jsr:@supabase/functions-js/edge-runtime.d.ts'
import { admin, requireAdmin } from '../_shared/admin.ts'
import { json, preflight } from '../_shared/cors.ts'
import { createInstance, deleteInstance as evolutionDeleteInstance } from '../_shared/evolution.ts'
import { randomToken, slugify } from '../_shared/random.ts'

const WORKER_WEBHOOK_URL_BASE = (Deno.env.get('WORKER_WEBHOOK_URL_BASE') ?? 'http://wa-mancer-worker:8090/webhook').replace(/\/$/, '')

const MAX_DISPLAY_NAME_LEN = 80

function validateDisplayName(v: unknown): string | null {
  if (typeof v !== 'string') return null
  const trimmed = v.trim()
  if (trimmed.length < 1 || trimmed.length > MAX_DISPLAY_NAME_LEN) return null
  // No control chars
  if (/[\x00-\x1f\x7f]/.test(trimmed)) return null
  return trimmed
}

Deno.serve(async (req) => {
  const pre = preflight(req); if (pre) return pre
  if (req.method !== 'POST') return json({ ok: false, reason: 'method_not_allowed' }, { status: 405 })

  const caller = await requireAdmin(req)
  if (!caller) return json({ ok: false, reason: 'forbidden' }, { status: 403 })

  let raw: unknown
  try { raw = await req.json() }
  catch { return json({ ok: false, reason: 'invalid_input' }, { status: 400 }) }

  const displayName = validateDisplayName((raw as { display_name?: unknown })?.display_name)
  if (!displayName) return json({ ok: false, reason: 'invalid_display_name' }, { status: 400 })

  // Allocate identifiers
  const evolutionInstanceName = `${slugify(displayName)}-${randomToken(8).toLowerCase()}`
  const perInstanceToken = randomToken(48)
  const webhookSecret = randomToken(48)

  // L1 (iGrowFast): every instance belongs to the caller's business and is placed on a
  // WhatsApp node. Placement = least-loaded ACTIVE node with capacity headroom (owner
  // governs the fleet via whatsapp.wa_nodes; business→node pinning layers on later as
  // assignment-data per blueprint §13.2).
  const { data: nodes, error: nodeErr } = await admin
    .schema('whatsapp')
    .from('wa_nodes')
    .select('id, max_instances')
    .eq('is_active', true)
  if (nodeErr || !nodes?.length) {
    return json({ ok: false, reason: 'no_node_available', error: nodeErr?.message }, { status: 503 })
  }
  const { data: placed } = await admin
    .schema('whatsapp')
    .from('whatsapp_instances')
    .select('node_id')
  const load = new Map<number, number>()
  for (const r of (placed ?? []) as Array<{ node_id: number | null }>) {
    if (r.node_id != null) load.set(r.node_id, (load.get(r.node_id) ?? 0) + 1)
  }
  const candidates = (nodes as Array<{ id: number; max_instances: number | null }>)
    .filter((n) => n.max_instances == null || (load.get(n.id) ?? 0) < n.max_instances)
    .sort((a, b) => (load.get(a.id) ?? 0) - (load.get(b.id) ?? 0))
  if (!candidates.length) {
    return json({ ok: false, reason: 'fleet_at_capacity' }, { status: 503 })
  }
  const nodeId = candidates[0].id

  // 1. INSERT row. The id (uuid) is generated by Postgres default; we read
  // it back. The auto-create trigger on whatsapp_instances also stamps the
  // number_pacing_state row.
  const { data: created, error: insertErr } = await admin
    .schema('whatsapp')
    .from('whatsapp_instances')
    .insert({
      display_name: displayName,
      evolution_instance_name: evolutionInstanceName,
      created_by: caller.uid,
      business_id: caller.businessId,
      node_id: nodeId,
      status: 'pending',
      lifecycle_state: 'warming',
    })
    .select('id')
    .single()

  if (insertErr || !created) {
    return json({ ok: false, reason: 'db_insert_failed', error: insertErr?.message }, { status: 500 })
  }
  const instanceId = created.id as string

  // 2. Store encrypted token + webhook secret. RPC helpers self-check
  // `is_admin()` from the JWT, so call them via the CALLER's JWT-scoped
  // client (we already verified they're admin in requireAdmin above).
  const [{ error: tokenErr }, { error: secretErr }] = await Promise.all([
    caller.client.schema('whatsapp').rpc('set_instance_token', { p_instance_id: instanceId, p_token: perInstanceToken }),
    caller.client.schema('whatsapp').rpc('set_instance_webhook_secret', { p_instance_id: instanceId, p_secret: webhookSecret }),
  ])
  if (tokenErr || secretErr) {
    await admin.schema('whatsapp').from('whatsapp_instances').delete().eq('id', instanceId)
    return json({
      ok: false, reason: 'secret_store_failed',
      error: tokenErr?.message ?? secretErr?.message,
    }, { status: 500 })
  }

  // 3. Provision at Evolution.
  const webhookUrl = `${WORKER_WEBHOOK_URL_BASE}/${instanceId}`
  const evo = await createInstance({
    instanceName: evolutionInstanceName,
    token: perInstanceToken,
    webhookUrl,
    webhookSecret,
  })
  if (!evo.ok) {
    // Best-effort remove any partially-created Evolution instance so we don't
    // leave an orphan (DB row gone, Evolution instance lingering), then clean up
    // the DB row so the name doesn't leak across retries.
    await evolutionDeleteInstance(evolutionInstanceName).catch(() => undefined)
    await admin.schema('whatsapp').from('whatsapp_instances').delete().eq('id', instanceId)
    return json({
      ok: false, reason: 'evolution_create_failed',
      status: evo.status, evolution_error: evo.body,
    }, { status: 502 })
  }

  return json({
    ok: true,
    instance: {
      id: instanceId,
      display_name: displayName,
      evolution_instance_name: evolutionInstanceName,
      status: 'pending',
    },
  }, { status: 201 })
})
