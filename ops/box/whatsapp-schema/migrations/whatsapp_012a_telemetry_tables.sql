-- whatsapp_012a_telemetry_tables.sql  (Wave 12a) — logs/telemetry stack (structure, empty)
-- TARGET: LIVE box .102 whatsapp ONLY. Port the observability tables 1:1 (structure only; WA Mancer's data
-- is NOT migrated — metrics/logs accumulate fresh from the iGrowFast worker/monitor). L1: the fleet surfaces
-- (system_logs, worker_health_history, host/db/metric/r2 metrics) are OWNER-gated (is_admin -> is_owner());
-- app_cache/og_cache/_cron_ingest_state are internal (service_role, SECDEF-accessed). NO anon anywhere.
-- id: metrics tables = GENERATED ALWAYS AS IDENTITY (matches WA Mancer attidentity='a'); system_logs +
-- worker_health_history = GENERATED BY DEFAULT AS IDENTITY (were sequences). metric_samples has NO PK (append-only).

-- NOTE: whatsapp.log_level + whatsapp.log_source enums already exist (created in the wave-3 enum block) with the
-- exact values needed; not re-created here.

-- ---------- internal cron cursor (no RLS)
create table whatsapp._cron_ingest_state (
  id boolean not null default true,
  last_runid bigint not null default 0,
  constraint _cron_ingest_state_pkey primary key (id),
  constraint _cron_ingest_state_id_check check (id)
);
grant select,insert,update,delete on whatsapp._cron_ingest_state to service_role;

-- ---------- dashboard cache (RLS on, no policy: SECDEF cache_get_or_compute accesses it)
create table whatsapp.app_cache (
  cache_key text not null,
  payload jsonb not null,
  computed_at timestamptz not null default now(),
  fresh_until timestamptz not null,
  hard_until timestamptz not null,
  delta_ms integer not null default 0,
  constraint app_cache_pkey primary key (cache_key)
);
create index app_cache_hard_until_idx on whatsapp.app_cache using btree (hard_until);
alter table whatsapp.app_cache enable row level security;
grant select,insert,update,delete on whatsapp.app_cache to service_role;

-- ---------- OpenGraph link-preview cache (RLS on, no policy)
create table whatsapp.og_cache (
  url_hash text not null,
  url text not null,
  payload jsonb,
  fetched_at timestamptz not null default now(),
  fresh_until timestamptz not null default (now() + interval '24 hours'),
  constraint og_cache_pkey primary key (url_hash)
);
create index og_cache_fresh_until_idx on whatsapp.og_cache using btree (fresh_until);
alter table whatsapp.og_cache enable row level security;
grant select,insert,update,delete on whatsapp.og_cache to service_role;

-- ---------- db metrics history (fleet, owner-gated)
create table whatsapp.db_metrics_history (
  id bigint generated always as identity,
  captured_at timestamptz not null default now(),
  source text not null,
  db_size_bytes bigint, conn_total integer, conn_active integer, conn_idle integer, conn_idle_in_txn integer,
  max_connections integer, cache_hit_pct double precision, xact_commit bigint, xact_rollback bigint,
  tup_inserted bigint, tup_updated bigint, tup_deleted bigint,
  constraint db_metrics_history_pkey primary key (id)
);
create index db_metrics_history_src_idx on whatsapp.db_metrics_history using btree (source, captured_at desc);
alter table whatsapp.db_metrics_history enable row level security;
create policy db_metrics_history_owner_select on whatsapp.db_metrics_history for select to authenticated using (public.is_owner());
grant select on whatsapp.db_metrics_history to authenticated; grant all on whatsapp.db_metrics_history to service_role;

