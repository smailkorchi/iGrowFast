-- ---------- system logs (fleet, owner-gated)
create table whatsapp.system_logs (
  id bigint generated by default as identity,
  occurred_at timestamptz not null default now(),
  source whatsapp.log_source not null,
  level whatsapp.log_level not null default 'info',
  event text not null,
  worker_id text, instance_id uuid, conversation_id uuid, actor_uid uuid,
  target_type text, target_id text,
  payload jsonb not null default '{}'::jsonb,
  platform_id text,
  constraint system_logs_pkey primary key (id)
);
create index system_logs_event_idx on whatsapp.system_logs using btree (event);
create index system_logs_instance_idx on whatsapp.system_logs using btree (instance_id) where (instance_id is not null);
create index system_logs_level_idx on whatsapp.system_logs using btree (level);
create index system_logs_occurred_idx on whatsapp.system_logs using btree (occurred_at desc, id desc);
create unique index system_logs_platform_id_uidx on whatsapp.system_logs using btree (source, platform_id) where (platform_id is not null);
create index system_logs_source_idx on whatsapp.system_logs using btree (source);
alter table whatsapp.system_logs enable row level security;
create policy system_logs_owner_select on whatsapp.system_logs for select to authenticated using (public.is_owner());
grant select on whatsapp.system_logs to authenticated; grant all on whatsapp.system_logs to service_role;

