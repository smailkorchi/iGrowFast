create trigger whatsapp_instances_audit after insert or delete or update on whatsapp.whatsapp_instances
  for each row execute function whatsapp._on_whatsapp_instance_change();
create trigger whatsapp_instances_config_audit after update of lifecycle_state, worker_paused, paired_at on whatsapp.whatsapp_instances
  for each row execute function whatsapp._on_instance_config_change();
