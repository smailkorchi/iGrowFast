-- ============================================================ RLS (admin-only; agent SELECT -> wave 8)
create policy wi_admin_insert on whatsapp.whatsapp_instances for insert to authenticated
  with check (
    public.current_user_is_business_admin()
    and business_id = public.current_user_digicom_business_id()
    and created_by = (select auth.uid())
  );
create policy wi_admin_update on whatsapp.whatsapp_instances for update to authenticated
  using (whatsapp.is_wa_admin(id)) with check (whatsapp.is_wa_admin(id));
create policy wi_admin_delete on whatsapp.whatsapp_instances for delete to authenticated
  using (whatsapp.is_wa_admin(id));
create policy wi_select on whatsapp.whatsapp_instances for select to authenticated
  using (whatsapp.is_wa_admin(id));   -- wave 8: ALTER to add "OR agent-assigned" branch

