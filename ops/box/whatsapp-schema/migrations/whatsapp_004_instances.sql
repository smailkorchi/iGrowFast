-- ============================================================ is_wa_admin (L1 role helper; needs the table above)
create or replace function whatsapp.is_wa_admin(p_instance_id uuid)
returns boolean language sql stable security definer set search_path to '' as $function$
  select public.current_user_is_business_admin()
     and exists (
       select 1 from whatsapp.whatsapp_instances i
       where i.id = p_instance_id
         and i.business_id = public.current_user_digicom_business_id()
     );
$function$;
revoke all on function whatsapp.is_wa_admin(uuid) from public;
grant  execute on function whatsapp.is_wa_admin(uuid) to authenticated, service_role;

-- ============================================================ config/audit triggers (port + whatsapp.audit)
create or replace function whatsapp._on_whatsapp_instance_change()
returns trigger language plpgsql security definer set search_path to '' as $function$
begin
  if TG_OP = 'INSERT' then
    perform whatsapp.audit('instance_created', 'instance', NEW.id::text,
      jsonb_build_object('display_name', NEW.display_name, 'evolution_instance_name', NEW.evolution_instance_name));
    return NEW;
  elsif TG_OP = 'UPDATE' then
    if OLD.status is distinct from NEW.status then
      perform whatsapp.audit('instance_status_changed', 'instance', NEW.id::text,
        jsonb_build_object('old', OLD.status, 'new', NEW.status));
    end if;
    if OLD.phone_number is distinct from NEW.phone_number then
      perform whatsapp.audit('instance_phone_bound', 'instance', NEW.id::text,
        jsonb_build_object('phone_number', NEW.phone_number));
    end if;
    return NEW;
  elsif TG_OP = 'DELETE' then
    perform whatsapp.audit('instance_deleted', 'instance', OLD.id::text, '{}'::jsonb);
    return OLD;
  end if;
  return NEW;
end;
$function$;

create or replace function whatsapp._on_instance_config_change()
returns trigger language plpgsql security definer set search_path to '' as $function$
begin
  if NEW.lifecycle_state is distinct from OLD.lifecycle_state then
    perform whatsapp.audit('instance_lifecycle_changed', 'instance', NEW.id::text,
      jsonb_build_object('old', OLD.lifecycle_state, 'new', NEW.lifecycle_state));
  end if;
  if NEW.worker_paused is distinct from OLD.worker_paused then
    perform whatsapp.audit(
      case when NEW.worker_paused then 'instance_paused' else 'instance_resumed' end,
      'instance', NEW.id::text, '{}'::jsonb);
  end if;
  if NEW.paired_at is not null and OLD.paired_at is null then
    perform whatsapp.audit('instance_first_paired', 'instance', NEW.id::text,
      jsonb_build_object('paired_at', NEW.paired_at));
  end if;
  return NEW;
end;
$function$;

revoke all on function whatsapp._on_whatsapp_instance_change() from public;
grant  execute on function whatsapp._on_whatsapp_instance_change() to service_role;
revoke all on function whatsapp._on_instance_config_change() from public;
grant  execute on function whatsapp._on_instance_config_change() to service_role;

