-- ============================================================ wa_nodes (NEW seam, deny-all)
create table whatsapp.wa_nodes (
  id            smallint generated by default as identity primary key,
  name          text not null unique,
  base_url_ct   bytea,                                   -- encrypted tailnet base url (key_id below)
  key_id        smallint not null default 1 references whatsapp.encryption_keys(key_id),
  is_active     boolean not null default true,
  max_instances integer,
  region        text,
  created_at    timestamptz not null default now(),
  note          text
);
alter table whatsapp.wa_nodes enable row level security;
revoke all on table whatsapp.wa_nodes from public;
-- deny-all: RLS on, zero policies, no anon/authenticated/service_role grants (read only via SECDEF node fns).

