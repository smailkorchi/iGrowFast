    capital_social = NULLIF(btrim(COALESCE(p_capital_social, '')), ''),
    legal_address = NULLIF(btrim(COALESCE(p_legal_address, '')), ''),
    legal_city = NULLIF(btrim(COALESCE(p_legal_city, '')), ''),
