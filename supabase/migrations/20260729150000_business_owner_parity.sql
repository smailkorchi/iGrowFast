    name = trim(p_name),
    logo = NULLIF(btrim(COALESCE(p_logo, '')), ''),
    ice = NULLIF(btrim(COALESCE(p_ice, '')), ''),
    rc = NULLIF(btrim(COALESCE(p_rc, '')), ''),
    identifiant_fiscal = NULLIF(btrim(COALESCE(p_identifiant_fiscal, '')), ''),
